/** Standardtext in die Dokumentsprache übersetzen; unbekannte Texte bleiben unverändert. */
export function tr(lang: DocLanguage | string | null | undefined, s: string): string {
  return lang === 'en' ? (EN[s] ?? s) : s;
}

export function isValidTimeZone(tz: string) {
  try {
    new Intl.DateTimeFormat('en-US', { timeZone: tz });
    return true;
  } catch {
    return false;
  }
}

/** Ortsdatum (YYYY-MM-DD) und Wochentag (0 = Sonntag) in einer Zeitzone. */
export function zonedDay(t: number, timeZone: string) {
  const tz = isValidTimeZone(timeZone) ? timeZone : 'Europe/Berlin';
  const parts = new Intl.DateTimeFormat('en-CA', { timeZone: tz, year: 'numeric', month: '2-digit', day: '2-digit', weekday: 'short' }).formatToParts(t);
  const get = (k: string) => parts.find((p) => p.type === k)?.value ?? '';
  return { ymd: `${get('year')}-${get('month')}-${get('day')}`, weekday: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].indexOf(get('weekday')) };
}

